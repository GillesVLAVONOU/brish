BEGIN;

CREATE TABLE IF NOT EXISTS ventes (
    id_vente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_vente DATE NOT NULL,
    id_utilisateur INTEGER REFERENCES utilisateurs(id_utilisateur) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS lignes_vente (
    id_ligne_vente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vente INTEGER NOT NULL REFERENCES ventes(id_vente) ON DELETE CASCADE,
    id_production INTEGER NOT NULL REFERENCES productions(id_production),
    portions_vendues INTEGER NOT NULL CHECK (portions_vendues > 0),
    prix_unitaire_applique DECIMAL(10,2) NOT NULL CHECK (prix_unitaire_applique >= 0),
    UNIQUE (id_vente, id_production)
);

CREATE INDEX IF NOT EXISTS idx_lignes_vente_production ON lignes_vente(id_production);
CREATE INDEX IF NOT EXISTS idx_ventes_date ON ventes(date_vente);

ALTER TABLE autorisations_role
    DROP CONSTRAINT IF EXISTS autorisations_role_role_check;
ALTER TABLE autorisations_role
    ADD CONSTRAINT autorisations_role_role_check
    CHECK (role IN ('ADMINISTRATEUR', 'GESTIONNAIRE', 'CUISINIER')) NOT VALID;

ALTER TABLE autorisations_role
    DROP CONSTRAINT IF EXISTS autorisations_role_module_check;
ALTER TABLE autorisations_role
    ADD CONSTRAINT autorisations_role_module_check
    CHECK (module IN (
        'DASHBOARD', 'INGREDIENTS', 'FOURNISSEURS', 'ACHATS', 'METS',
        'RECETTES', 'PRODUCTIONS', 'VENTES', 'RAPPORTS', 'PARAMETRES'
    ));

ALTER TABLE autorisations_utilisateur
    DROP CONSTRAINT IF EXISTS autorisations_utilisateur_module_check;
ALTER TABLE autorisations_utilisateur
    ADD CONSTRAINT autorisations_utilisateur_module_check
    CHECK (module IN (
        'DASHBOARD', 'INGREDIENTS', 'FOURNISSEURS', 'ACHATS', 'METS',
        'RECETTES', 'PRODUCTIONS', 'VENTES', 'RAPPORTS', 'PARAMETRES'
    ));

INSERT INTO autorisations_role (role, module, peut_consulter, peut_modifier)
VALUES
    ('ADMINISTRATEUR', 'VENTES', TRUE, TRUE),
    ('GESTIONNAIRE', 'VENTES', TRUE, TRUE),
    ('CUISINIER', 'VENTES', FALSE, FALSE)
ON CONFLICT (role, module) DO NOTHING;

COMMIT;
