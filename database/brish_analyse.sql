CREATE TABLE utilisateurs (
    id_utilisateur INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    mot_de_passe_hash VARCHAR(255) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    role VARCHAR(50) NOT NULL CHECK (role IN ('ADMINISTRATEUR', 'GESTIONNAIRE', 'CUISINIER'))
);

CREATE TABLE reinitialisations_mot_de_passe (
    id_reinitialisation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_utilisateur INTEGER NOT NULL REFERENCES utilisateurs(id_utilisateur) ON DELETE CASCADE,
    jeton_hash CHAR(64) NOT NULL UNIQUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expire_le TIMESTAMPTZ NOT NULL,
    utilise_le TIMESTAMPTZ,
    CHECK (expire_le > cree_le)
);

CREATE INDEX idx_reinitialisations_mdp_utilisateur
    ON reinitialisations_mot_de_passe (id_utilisateur, cree_le DESC);

CREATE INDEX idx_reinitialisations_mdp_expiration
    ON reinitialisations_mot_de_passe (expire_le)
    WHERE utilise_le IS NULL;

CREATE TABLE ingredients (
    id_ingredient INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(120) NOT NULL UNIQUE,
    unite_base VARCHAR(20) NOT NULL,
    seuil_alerte DECIMAL(10,3),
    actif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE fournisseurs (
    id_fournisseur INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    telephone VARCHAR(30),
    email VARCHAR(150) UNIQUE,
    adresse VARCHAR(255)
);

CREATE TABLE achats (
    id_achat INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fournisseur INTEGER NOT NULL REFERENCES fournisseurs(id_fournisseur),
    date_achat DATE NOT NULL,
    numero_facture VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE lignes_achat (
    id_ligne_achat INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_achat INTEGER NOT NULL REFERENCES achats(id_achat) ON DELETE CASCADE,
    id_ingredient INTEGER NOT NULL REFERENCES ingredients(id_ingredient),
    quantite DECIMAL(10,3) NOT NULL,
    unite VARCHAR(20) NOT NULL,
    prix_unitaire DECIMAL(10,2) NOT NULL
);

CREATE TABLE mets (
    id_met INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(120) NOT NULL,
    description TEXT,
    prix_vente_actuel DECIMAL(10,2) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE recettes (
    id_recette INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_met INTEGER NOT NULL REFERENCES mets(id_met),
    version INTEGER NOT NULL,
    rendement_portions INTEGER NOT NULL CHECK (rendement_portions > 0),
    date_effet DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (id_met, version)
);

CREATE TABLE lignes_recette (
    id_ligne_recette INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recette INTEGER NOT NULL REFERENCES recettes(id_recette) ON DELETE CASCADE,
    id_ingredient INTEGER NOT NULL REFERENCES ingredients(id_ingredient),
    quantite DECIMAL(10,3) NOT NULL,
    unite VARCHAR(20) NOT NULL
);

CREATE TABLE productions (
    id_production INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recette INTEGER NOT NULL REFERENCES recettes(id_recette),
    id_utilisateur INTEGER REFERENCES utilisateurs(id_utilisateur),
    date_production TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_cloture DATE,
    portions_prevues INTEGER NOT NULL CHECK (portions_prevues > 0),
    portions_reelles INTEGER,
    statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON'
);

CREATE TABLE lignes_production (
    id_ligne_production INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_production INTEGER NOT NULL REFERENCES productions(id_production) ON DELETE CASCADE,
    id_ingredient INTEGER NOT NULL REFERENCES ingredients(id_ingredient),
    quantite_reelle DECIMAL(10,3) NOT NULL,
    unite VARCHAR(20) NOT NULL,
    cout_unitaire_applique DECIMAL(10,2) NOT NULL,
    cout_total DECIMAL(10,2) NOT NULL
);

CREATE TABLE charges_production (
    id_charge_production INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_production INTEGER NOT NULL REFERENCES productions(id_production) ON DELETE CASCADE,
    libelle VARCHAR(120) NOT NULL,
    montant DECIMAL(10,2) NOT NULL,
    methode_affectation VARCHAR(30) NOT NULL
);

CREATE TABLE historique_couts (
    id_historique INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_production INTEGER NOT NULL REFERENCES productions(id_production),
    date_calcul TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cout_matiere DECIMAL(10,2) NOT NULL,
    cout_charges DECIMAL(10,2) NOT NULL,
    cout_total DECIMAL(10,2) NOT NULL,
    cout_unitaire DECIMAL(10,2) NOT NULL
);

CREATE TABLE ventes (
    id_vente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_vente DATE NOT NULL,
    id_utilisateur INTEGER REFERENCES utilisateurs(id_utilisateur) ON DELETE SET NULL
);

CREATE TABLE lignes_vente (
    id_ligne_vente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vente INTEGER NOT NULL REFERENCES ventes(id_vente) ON DELETE CASCADE,
    id_production INTEGER NOT NULL REFERENCES productions(id_production),
    portions_vendues INTEGER NOT NULL CHECK (portions_vendues > 0),
    prix_unitaire_applique DECIMAL(10,2) NOT NULL CHECK (prix_unitaire_applique >= 0),
    UNIQUE (id_vente, id_production)
);

CREATE INDEX idx_lignes_achat_ingredient ON lignes_achat(id_ingredient);
CREATE INDEX idx_lignes_recette_ingredient ON lignes_recette(id_ingredient);
CREATE INDEX idx_productions_recette ON productions(id_recette);
CREATE INDEX idx_historique_couts_production ON historique_couts(id_production);
CREATE INDEX idx_lignes_vente_production ON lignes_vente(id_production);
CREATE INDEX idx_ventes_date ON ventes(date_vente);
