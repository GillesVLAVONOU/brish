DROP TABLE IF EXISTS historique_couts CASCADE;
DROP TABLE IF EXISTS charges_production CASCADE;
DROP TABLE IF EXISTS lignes_production CASCADE;
DROP TABLE IF EXISTS productions CASCADE;
DROP TABLE IF EXISTS lignes_recette CASCADE;
DROP TABLE IF EXISTS recettes CASCADE;
DROP TABLE IF EXISTS mets CASCADE;
DROP TABLE IF EXISTS lignes_achat CASCADE;
DROP TABLE IF EXISTS achats CASCADE;
DROP TABLE IF EXISTS fournisseurs CASCADE;
DROP TABLE IF EXISTS ingredients CASCADE;
DROP TABLE IF EXISTS utilisateurs CASCADE;
DROP TABLE IF EXISTS parametres_restaurant CASCADE;

CREATE TABLE parametres_restaurant (
    id_parametres SMALLINT PRIMARY KEY CHECK (id_parametres = 1),
    nom_restaurant VARCHAR(120) NOT NULL,
    adresse VARCHAR(255),
    telephone VARCHAR(30),
    code_devise CHAR(3) NOT NULL DEFAULT 'XOF'
        CHECK (code_devise IN ('XOF', 'XAF', 'NGN', 'GHS', 'EUR', 'USD'))
);

